package fi.alavesa.facility;

import net.kyori.adventure.key.Key;
import net.kyori.adventure.sound.Sound;
import net.kyori.adventure.sound.SoundStop;
import org.bukkit.entity.Player;
import org.bukkit.scheduler.BukkitTask;

import java.lang.reflect.Method;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.UUID;
import java.util.concurrent.ThreadLocalRandom;
import java.util.function.IntFunction;

/**
 * Everything the main menu does to the player's screen and speakers besides
 * the dialog itself: the monitor look behind the menu, the transition
 * animations, the looping music and the transition sounds.
 *
 * VISUALS are Minecraft 26.3 post effects: {@code Player.postEffects()} sends
 * a ClientboundPostEffectsPacket naming post_effect JSONs from the resource
 * pack (facility:menu_*, generated by tools/gen_menu_fx.py). A post effect's
 * values are fixed, so an animation is a run of numbered variants that we step
 * through one per tick. The client draws post effects BEFORE the GUI, so the
 * dialog stays clean on top - and it blurs what is behind it, so the look is
 * soft while a dialog is open and crisp during the transitions.
 *
 * On a server without that API (Minecraft below 26.3) the visuals are skipped
 * and nothing waits on them; music, sounds and the menu itself work as before.
 *
 * One {@link Session} per player in the menu:
 *   {@link #enter}    menu opened - music + intro (monitor powers on)
 *   {@link #navigate} a button opened another dialog - click + static burst
 *   {@link #deploy}   PLAY - static + power-off, black while the caller
 *                     teleports, then the game picture fades in
 *   {@link #leave}    hard stop (quit, shutdown)
 * All of it runs on the main thread.
 */
public final class MenuAudioAndVisualPacketHandler {

    /** Frames per animation - MUST match FRAMES in tools/gen_menu_fx.py. */
    private static final int FRAMES = 12;
    private static final String NAMESPACE = "facility";
    private static final String PREFIX = "menu_";

    private final FacilityPlugin plugin;
    private MenuSettings settings;
    private final Map<UUID, Session> sessions = new java.util.concurrent.ConcurrentHashMap<>();

    private static final class Session {
        String effect;          // the facility:menu_* effect we currently have on the player, or null
        BukkitTask animation;   // frame stepper in flight
        BukkitTask arrival;     // the deploy's teleport, scheduled apart from the frames so it can't be lost
        BukkitTask music;       // starts the next track
        int track = -1;
        boolean deploying;      // PLAY pressed: no more menu effects
        boolean arrived;        // ...and the player is already in the world (reveal running)
    }

    public MenuAudioAndVisualPacketHandler(FacilityPlugin plugin) {
        this.plugin = plugin;
        this.settings = MenuSettings.load(plugin);
        if (settings.shader().enabled() && !PostEffects.AVAILABLE) {
            plugin.getLogger().info("Player.postEffects() not available (Minecraft < 26.3): "
                + "the menu runs without its shader look and visual transitions.");
        }
    }

    /** Re-read config (/facility reload) and restyle everyone sitting in the menu. */
    public void reload() {
        settings = MenuSettings.load(plugin);
        for (Map.Entry<UUID, Session> e : sessions.entrySet()) {
            Player player = plugin.getServer().getPlayer(e.getKey());
            Session s = e.getValue();
            if (player == null || s.deploying) continue;
            stopAnimation(s);
            show(player, s, idle());
            stopMusic(player, s);
            playNextTrack(player, s);
        }
    }

    public MenuSettings settings() {
        return settings;
    }

    // --- menu lifecycle -----------------------------------------------------

    /** The player is in the menu. Idempotent - LobbyManager calls this on every
     *  dialog (re)send - so only the first call starts the music and the intro. */
    public void enter(Player player) {
        try {
            begin(player);
        } catch (RuntimeException | LinkageError e) {
            // The menu must open whatever happens in here (LobbyManager.beginMenu stays dumb).
            plugin.getLogger().warning("Menu look/music failed for " + player.getName() + ": " + e);
        }
    }

    private void begin(Player player) {
        UUID id = player.getUniqueId();
        Session old = sessions.get(id);
        if (old != null) {
            if (!old.arrived) return;   // already in the menu, or mid-PLAY
            leave(player);              // back in the menu while the last reveal was still running
        }
        Session s = new Session();
        sessions.put(id, s);
        playNextTrack(player, s);

        MenuSettings.Transitions tr = settings.transitions();
        if (visuals() && tr.enabled() && tr.introTicks() > 0) {
            play(player, tr.bootSound());
            // the power-off frames, backwards: black -> the tube opens up -> the static settles
            animate(player, s, tr.introTicks(), i -> frame(tr.glitch() ? "out" : "fade", FRAMES + 1 - i),
                () -> show(player, s, idle()));
        } else {
            show(player, s, idle());
        }
    }

    /** A dialog button led to another dialog: a click and a short static burst. */
    public void navigate(Player player) {
        try {
            burst(player);
        } catch (RuntimeException | LinkageError e) {
            plugin.getLogger().warning("Menu transition failed for " + player.getName() + ": " + e);
        }
    }

    private void burst(Player player) {
        Session s = sessions.get(player.getUniqueId());
        if (s == null || s.deploying) return;
        MenuSettings.Transitions tr = settings.transitions();
        if (!tr.enabled()) return;
        play(player, tr.clickSound());
        if (!visuals() || !tr.glitch() || tr.navigateTicks() <= 0) return;
        play(player, tr.glitchSound());
        stopAnimation(s);
        show(player, s, PREFIX + settings.shader().look() + "_glitch");
        s.animation = plugin.getServer().getScheduler().runTaskLater(plugin, () -> {
            s.animation = null;
            if (player.isOnline()) show(player, s, idle());
        }, tr.navigateTicks());
    }

    /**
     * PLAY. Runs the out-transition, calls {@code arrive} (the teleport) while
     * the screen is black, then fades the game picture in and ends the session.
     * {@code arrive} runs exactly once unless the player quits first; with
     * transitions off, or no session, it runs right now.
     */
    public void deploy(Player player, Runnable arrive) {
        boolean[] ran = {false};
        Runnable once = () -> { if (!ran[0]) { ran[0] = true; arrive.run(); } };
        try {
            transitionOut(player, once);
        } catch (RuntimeException | LinkageError e) {
            // Whatever broke, the player pressed PLAY: get them into the world.
            plugin.getLogger().warning("Menu transition failed for " + player.getName() + ": " + e);
            leave(player);
            once.run();
        }
    }

    private void transitionOut(Player player, Runnable arrive) {
        UUID id = player.getUniqueId();
        Session s = sessions.get(id);
        MenuSettings.Transitions tr = settings.transitions();
        if (s == null || s.deploying || !tr.enabled()) {
            leave(player);
            arrive.run();
            return;
        }
        s.deploying = true;
        stopAnimation(s);
        play(player, tr.deploySound());

        // Without the shader there is nothing to watch, so nothing to wait for.
        int out = visuals() ? tr.deployTicks() : 0;
        if (out > 0) {
            animate(player, s, out, i -> frame(tr.glitch() ? "out" : "fade", i), null);
        }
        Runnable landing = () -> {
            s.arrival = null;
            stopAnimation(s);
            if (!player.isOnline()) { leave(player); return; }
            if (visuals()) show(player, s, PREFIX + "black");
            stopMusic(player, s);
            s.arrived = true;
            try {
                arrive.run();
            } finally {
                reveal(player, s);
            }
        };
        if (out > 0) s.arrival = plugin.getServer().getScheduler().runTaskLater(plugin, landing, out);
        else landing.run();
    }

    /** After the teleport: hold black while the destination loads, fade the
     *  untouched game picture in, then drop our effect and the session. */
    private void reveal(Player player, Session s) {
        MenuSettings.Transitions tr = settings.transitions();
        Runnable end = () -> { if (sessions.get(player.getUniqueId()) == s) leave(player); };
        if (!visuals() || tr.revealTicks() <= 0) { end.run(); return; }
        s.animation = plugin.getServer().getScheduler().runTaskLater(plugin, () -> {
            s.animation = null;
            if (!player.isOnline()) { end.run(); return; }
            animate(player, s, tr.revealTicks(), i -> PREFIX + "reveal_" + two(i), end);
        }, tr.holdTicks());
    }

    /** Hard stop: no more music, effects or tasks for this player. Safe to call anytime. */
    public void leave(Player player) {
        Session s = sessions.remove(player.getUniqueId());
        if (s == null) return;
        stopAnimation(s);
        if (s.arrival != null) s.arrival.cancel();
        stopMusic(player, s);
        if (player.isOnline()) show(player, s, null);
    }

    /** Safety net for LobbyManager's reconcile tick: a player who is in the
     *  world has no business keeping the menu look. A deploy in flight is left alone. */
    public void ensureLeft(Player player) {
        Session s = sessions.get(player.getUniqueId());
        if (s != null && !s.deploying) leave(player);
    }

    /** Plugin disable: give everyone their screen back. */
    public void shutdown() {
        for (UUID id : new ArrayList<>(sessions.keySet())) {
            Player player = plugin.getServer().getPlayer(id);
            if (player != null) leave(player);
        }
        sessions.clear();
    }

    // --- admin preview (/facility menu preview ...) -------------------------

    /** Play one transition on an admin who is NOT in the menu, so shader and
     *  timing settings can be tuned without rejoining. Returns false if busy. */
    public boolean preview(Player player, String what) {
        if (sessions.containsKey(player.getUniqueId())) return false;
        Session s = new Session();
        s.deploying = true;   // not a menu session: keeps navigate() and ensureLeft() off it
        sessions.put(player.getUniqueId(), s);
        MenuSettings.Transitions tr = settings.transitions();
        Runnable end = () -> { if (sessions.get(player.getUniqueId()) == s) leave(player); };
        Runnable lookThenEnd = () -> {
            show(player, s, idle());
            s.animation = plugin.getServer().getScheduler().runTaskLater(plugin, end, 60L);
        };
        switch (what.toLowerCase(Locale.ROOT)) {
            case "intro" -> {
                play(player, tr.bootSound());
                animate(player, s, Math.max(1, tr.introTicks()),
                    i -> frame(tr.glitch() ? "out" : "fade", FRAMES + 1 - i), lookThenEnd);
            }
            case "glitch" -> {
                play(player, tr.clickSound());
                play(player, tr.glitchSound());
                show(player, s, PREFIX + settings.shader().look() + "_glitch");
                s.animation = plugin.getServer().getScheduler().runTaskLater(plugin, lookThenEnd,
                    Math.max(1, tr.navigateTicks()));
            }
            case "deploy" -> {
                show(player, s, idle());
                play(player, tr.deploySound());
                animate(player, s, Math.max(1, tr.deployTicks()), i -> frame(tr.glitch() ? "out" : "fade", i), () -> {
                    show(player, s, PREFIX + "black");
                    s.arrived = true;
                    reveal(player, s);
                });
            }
            default -> lookThenEnd.run();   // "look": just the idle look for 3 seconds
        }
        return true;
    }

    // --- frames -------------------------------------------------------------

    private boolean visuals() {
        return settings.shader().enabled() && PostEffects.AVAILABLE;
    }

    private String idle() {
        return PREFIX + settings.shader().look();
    }

    /** menu_&lt;look&gt;_&lt;kind&gt;_&lt;NN&gt; - kind is "out" or "fade", i is 1..FRAMES. */
    private String frame(String kind, int i) {
        return PREFIX + settings.shader().look() + "_" + kind + "_" + two(i);
    }

    private static String two(int i) {
        return (i < 10 ? "0" : "") + i;
    }

    /** Step through an animation's FRAMES frames over {@code ticks} ticks (a
     *  frame per tick at most; a longer animation holds each frame for longer),
     *  then run {@code done}. Replaces any animation already in flight. */
    private void animate(Player player, Session s, int ticks, IntFunction<String> frameAt, Runnable done) {
        stopAnimation(s);
        int[] tick = {0};
        show(player, s, frameAt.apply(1));
        s.animation = plugin.getServer().getScheduler().runTaskTimer(plugin, () -> {
            tick[0]++;
            if (!player.isOnline() || tick[0] >= ticks) {
                stopAnimation(s);
                if (done != null) done.run();
                return;
            }
            int i = Math.min(FRAMES, 1 + tick[0] * FRAMES / ticks);
            show(player, s, frameAt.apply(i));
        }, 1L, 1L);
    }

    private void stopAnimation(Session s) {
        if (s.animation != null) s.animation.cancel();
        s.animation = null;
    }

    /** Swap our effect on the player for {@code name} (null = none), leaving
     *  every other plugin's post effects (CCTV, night vision...) in place. */
    private void show(Player player, Session s, String name) {
        if (!visuals()) name = null;
        if (java.util.Objects.equals(name, s.effect)) return;
        s.effect = name;
        PostEffects.setOurs(player, name == null ? null : Key.key(NAMESPACE, name));
    }

    // --- sound --------------------------------------------------------------

    /** A one-shot transition sound that stays with the player through the teleport. */
    private void play(Player player, Key sound) {
        float volume = settings.transitions().volume();
        if (sound == null || volume <= 0f) return;
        player.playSound(Sound.sound(sound, Sound.Source.MASTER, volume, 1.0f), Sound.Emitter.self());
    }

    /**
     * Start the next menu track and book the one after it. A server can only
     * say "play this now", so the loop is: play, wait the track's length minus
     * {@code overlap-seconds}, play the next. With a fade of that length baked
     * into both ends of the .ogg the seam is a crossfade instead of a gap.
     */
    private void playNextTrack(Player player, Session s) {
        MenuSettings.Music music = settings.music();
        List<MenuSettings.Track> tracks = music.tracks();
        if (!music.enabled() || tracks.isEmpty() || music.volume() <= 0f) return;
        if (music.shuffle() && tracks.size() > 1) {
            int next = ThreadLocalRandom.current().nextInt(tracks.size() - 1);
            s.track = next >= s.track ? next + 1 : next;   // never the same track twice in a row
        } else {
            s.track = (s.track + 1) % tracks.size();
        }
        MenuSettings.Track track = tracks.get(s.track);
        // Emitter.self(): the music follows the player to the lobby vantage instead of staying where they logged in.
        player.playSound(Sound.sound(track.sound(), music.category(), music.volume(), music.pitch()),
            Sound.Emitter.self());
        double seconds = Math.max(1.0, (track.lengthSeconds() - music.overlapSeconds()) / music.pitch());
        s.music = plugin.getServer().getScheduler().runTaskLater(plugin, () -> {
            if (player.isOnline() && sessions.get(player.getUniqueId()) == s && !s.arrived) playNextTrack(player, s);
        }, Math.round(seconds * 20.0));
    }

    private void stopMusic(Player player, Session s) {
        if (s.music != null) s.music.cancel();
        s.music = null;
        if (!player.isOnline()) return;
        for (MenuSettings.Track track : settings.music().tracks()) {
            player.stopSound(SoundStop.named(track.sound()));
        }
    }

    // --- Player.postEffects() -----------------------------------------------

    /**
     * Paper's {@code Player.postEffects()} (PlayerPostEffects, Minecraft 26.3+),
     * bound by reflection because this plugin compiles against the 1.21.4 API.
     * The whole list is set in one call, so a frame change is one packet.
     */
    private static final class PostEffects {

        private static final Method POST_EFFECTS;
        private static final Method VALUES;
        private static final Method SET;
        static final boolean AVAILABLE;

        static {
            Method pe = null, values = null, set = null;
            try {
                pe = Player.class.getMethod("postEffects");
                Class<?> api = Class.forName("io.papermc.paper.entity.PlayerPostEffects");
                values = api.getMethod("values");
                set = api.getMethod("set", java.util.SequencedCollection.class);
            } catch (ReflectiveOperationException | LinkageError e) {
                pe = null;
            }
            POST_EFFECTS = pe;
            VALUES = values;
            SET = set;
            AVAILABLE = pe != null;
        }

        @SuppressWarnings("unchecked")
        static void setOurs(Player player, Key effect) {
            if (!AVAILABLE) return;
            try {
                Object api = POST_EFFECTS.invoke(player);
                List<Key> current = (List<Key>) VALUES.invoke(api);
                List<Key> next = new ArrayList<>(current);
                next.removeIf(k -> k.namespace().equals(NAMESPACE) && k.value().startsWith(PREFIX));
                if (effect != null) next.add(effect);
                if (!next.equals(current)) SET.invoke(api, next);
            } catch (ReflectiveOperationException | RuntimeException e) {
                // nothing sensible to do: the menu works without its look
            }
        }
    }
}
